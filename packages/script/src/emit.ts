import type { CompiledNode, CompiledProgram, ExecLink } from './ir';
import { componentNames } from './world';

/**
 * Plain JavaScript for a compiled graph.
 * The module imports `createScriptHost` from `@jurfi/script/host` and does not import the interpreter.
 */
export function emitProgram(program: CompiledProgram): string {
  const emitter = new Emitter();
  emitter.emitGraph(program, 'root');
  return emitter.render(program);
}

function js(value: unknown): string {
  if (value === undefined) return 'undefined';
  return JSON.stringify(value);
}

function indent(lines: readonly string[], spaces: number): string[] {
  const pad = ' '.repeat(spaces);
  return lines.map((line) => (line.length === 0 ? '' : pad + line));
}

function sequenceIndex(name: string): number | null {
  const match = /^then(\d+)$/.exec(name);
  if (!match?.[1]) return null;
  return Number(match[1]);
}

function prop(node: CompiledNode, key: string): string {
  const value = node.props[key];
  return typeof value === 'string' ? value : '';
}

class Emitter {
  private readonly functions: string[] = [];
  private readonly listeners: string[] = [];
  private readonly execNames = new Map<string, string>();
  private readonly valueNames = new Map<string, string>();
  private seq = 0;
  private clamp = false;

  emitGraph(program: CompiledProgram, scope: string): void {
    for (const node of Object.values(program.nodes)) this.emitNode(program, scope, node);
    for (const [id, child] of Object.entries(program.subgraphs)) this.emitGraph(child, `${scope}/${id}`);
    for (const [eventName, ids] of Object.entries(program.entries.event)) {
      for (const nodeId of ids) {
        this.listeners.push(
          `  host.addListener(${js(scope)}, ${js(eventName)}, ${js(nodeId)}, ${this.execName(scope, nodeId)});`,
        );
      }
    }
  }

  render(program: CompiledProgram): string {
    const start = program.entries.start.map((id) => `    ${this.execName('root', id)}(host);`);
    const update = program.entries.update.map((id) => `    ${this.execName('root', id)}(host);`);
    const lines = [
      '// Generated by @jurfi/script for the game runtime.',
      this.clamp
        ? '// Imports the compiled script host and clamp from @jurfi/core.'
        : '// Imports the compiled script host.',
      'import { createScriptHost } from "@jurfi/script/host";',
    ];
    if (this.clamp) lines.push('import { clamp } from "@jurfi/core";');
    lines.push(
      '',
      `export const program = ${JSON.stringify(program, null, 2)};`,
      '',
      'export function createRuntime(options) {',
      '  const host = createScriptHost(options);',
      '  host.loadProgram(program);',
      '  host.bind({',
      '    start(host) {',
      ...start,
      '    },',
      '    update(host) {',
      ...update,
      '    },',
      '  });',
      ...this.listeners,
      '  return host;',
      '}',
      '',
      ...this.functions,
    );
    if (this.clamp) lines.push('', 'export { clamp };');
    lines.push('');
    return lines.join('\n');
  }

  private emitNode(program: CompiledProgram, scope: string, node: CompiledNode): void {
    if (node.typeId === 'core/Clamp') this.clamp = true;
    const exec = this.execName(scope, node.id);
    const value = this.valueName(scope, node.id);
    this.functions.push(this.renderExec(program, scope, node, exec));
    this.functions.push(this.renderValue(scope, node, value));
    this.functions.push('');
  }

  private execName(scope: string, nodeId: string): string {
    const key = `${scope}\0${nodeId}`;
    let name = this.execNames.get(key);
    if (!name) {
      this.seq += 1;
      name = `n${this.seq}`;
      this.execNames.set(key, name);
    }
    return name;
  }

  private valueName(scope: string, nodeId: string): string {
    const key = `${scope}\0${nodeId}`;
    let name = this.valueNames.get(key);
    if (!name) {
      this.seq += 1;
      name = `v${this.seq}`;
      this.valueNames.set(key, name);
    }
    return name;
  }

  private expr(scope: string, node: CompiledNode, pin: string): string {
    const src = node.dataIn[pin];
    if (!src) return 'undefined';
    if (src.kind === 'literal') return js(src.value);
    return `${this.valueName(scope, src.nodeId)}(host, ${js(src.pin)})`;
  }

  private calls(scope: string, links: ExecLink[] | undefined): string[] {
    if (!links || links.length === 0) return [];
    const lines: string[] = [];
    for (const link of links) {
      lines.push('if (host.halted) return;');
      lines.push(`${this.execName(scope, link.nodeId)}(host);`);
    }
    return lines;
  }

  private renderExec(program: CompiledProgram, scope: string, node: CompiledNode, name: string): string {
    const body = this.execBody(program, scope, node);
    return [
      `function ${name}(host) {`,
      '  if (host.halted) return;',
      `  if (!host.step(${js(node.id)})) return;`,
      '  try {',
      ...indent(body, 4),
      '  } catch (error) {',
      `    host.fault(${js(node.id)}, error);`,
      '  }',
      '}',
    ].join('\n');
  }

  private renderValue(scope: string, node: CompiledNode, name: string): string {
    return [
      `function ${name}(host, pin) {`,
      `  return host.readValue(${js(node.id)}, pin, () => {`,
      ...indent(this.valueBody(scope, node), 4),
      '  });',
      '}',
    ].join('\n');
  }

  private execBody(program: CompiledProgram, scope: string, node: CompiledNode): string[] {
    switch (node.typeId) {
      case 'core/OnStart':
      case 'core/OnUpdate':
      case 'core/OnEvent':
        return this.calls(scope, node.execOut.then);
      case 'core/FireEvent':
        return [
          `const fromPin = ${this.expr(scope, node, 'event')};`,
          `const name = typeof fromPin === "string" && fromPin !== "" ? fromPin : ${js(prop(node, 'event') || prop(node, 'name'))};`,
          `const payload = ${this.expr(scope, node, 'payload')};`,
          'if (name) host.dispatch(' + js(scope) + ', name, payload);',
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/Branch':
        return [
          `if (host.truthy(${this.expr(scope, node, 'condition')})) {`,
          ...indent(this.calls(scope, node.execOut.true), 2),
          '} else {',
          ...indent(this.calls(scope, node.execOut.false), 2),
          '}',
        ];
      case 'core/Sequence':
        return this.sequenceCalls(scope, node);
      case 'core/ForLoop':
        return [
          `const first = host.num(${this.expr(scope, node, 'first')});`,
          `const last = host.num(${this.expr(scope, node, 'last')});`,
          'for (let index = first; index <= last; index += 1) {',
          '  if (host.halted) return;',
          `  if (!host.step(${js(node.id)})) return;`,
          `  host.writeLoop(${js(scope)}, ${js(node.id)}, index);`,
          ...indent(this.calls(scope, node.execOut.body), 2),
          '}',
          ...this.calls(scope, node.execOut.completed),
        ];
      case 'core/While':
        return [
          `while (host.truthy(${this.expr(scope, node, 'condition')})) {`,
          '  if (host.halted) return;',
          `  if (!host.step(${js(node.id)})) return;`,
          ...indent(this.calls(scope, node.execOut.body), 2),
          '}',
          ...this.calls(scope, node.execOut.completed),
        ];
      case 'core/Delay':
        return [
          `host.delay(host.num(${this.expr(scope, node, 'seconds')}), () => {`,
          ...indent(this.calls(scope, node.execOut.then), 2),
          '});',
        ];
      case 'core/SetVariable':
        return [...this.writeVariable(scope, node), ...this.calls(scope, node.execOut.then)];
      case 'core/SpawnEntity':
        return [
          `host.rememberSpawn(${js(scope)}, ${js(node.id)}, host.spawn());`,
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/DestroyEntity':
        return [
          `host.destroy(host.entity(${this.expr(scope, node, 'entity')}));`,
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/AddComponent':
        return [
          `host.addComponent(host.entity(${this.expr(scope, node, 'entity')}), ${js(prop(node, 'component'))}, ${node.dataIn.value ? this.expr(scope, node, 'value') : 'undefined'});`,
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/RemoveComponent':
        return [
          `host.removeComponent(host.entity(${this.expr(scope, node, 'entity')}), ${js(prop(node, 'component'))});`,
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/ForEach':
        return [
          `const items = host.eachItems(${this.expr(scope, node, 'entities')});`,
          'for (let index = 0; index < items.length; index += 1) {',
          '  if (host.halted) return;',
          `  if (!host.step(${js(node.id)})) return;`,
          `  const item = items[index];`,
          '  if (item) host.rememberEach(' + js(scope) + ', ' + js(node.id) + ', item);',
          ...indent(this.calls(scope, node.execOut.body), 2),
          '}',
          ...this.calls(scope, node.execOut.completed),
        ];
      case 'core/SetComponent':
        return [
          `const component = ${js(prop(node, 'component'))};`,
          'if (component) {',
          `  host.world.setComponent(host.entity(${this.expr(scope, node, 'entity')}), component, ${this.expr(scope, node, 'value')});`,
          '}',
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/SetField':
        return [
          `const component = ${js(prop(node, 'component'))};`,
          `const field = ${js(prop(node, 'field'))};`,
          'if (component && field) {',
          `  host.setField(host.entity(${this.expr(scope, node, 'entity')}), component, field, ${this.expr(scope, node, 'value')});`,
          '}',
          ...this.calls(scope, node.execOut.then),
        ];
      case 'core/Subgraph':
        return [...this.subgraphCalls(program, scope, node), ...this.calls(scope, node.execOut.then)];
      case 'core/GetVariable':
      case 'core/Add':
      case 'core/Subtract':
      case 'core/Multiply':
      case 'core/Divide':
      case 'core/Clamp':
      case 'core/And':
      case 'core/Or':
      case 'core/Not':
      case 'core/Equal':
      case 'core/NotEqual':
      case 'core/Greater':
      case 'core/GreaterEqual':
      case 'core/Less':
      case 'core/LessEqual':
      case 'core/Self':
      case 'core/GetComponent':
      case 'core/GetField':
      case 'core/HasComponent':
      case 'core/Query':
        return [];
      default:
        return this.customExec(scope, node);
    }
  }

  private sequenceCalls(scope: string, node: CompiledNode): string[] {
    const pins = Object.keys(node.execOut)
      .map((name) => ({ name, index: sequenceIndex(name) }))
      .filter((pin): pin is { name: string; index: number } => pin.index !== null)
      .sort((a, b) => a.index - b.index);
    const lines: string[] = [];
    for (const pin of pins) lines.push(...this.calls(scope, node.execOut[pin.name]));
    return lines;
  }

  private writeVariable(scope: string, node: CompiledNode): string[] {
    const name = js(prop(node, 'name'));
    const value = this.expr(scope, node, 'value');
    if (node.props.scope === 'entity') {
      return [`host.entitySet(host.entity(${this.expr(scope, node, 'entity')}), ${name}, ${value});`];
    }
    return [`host.graphSet(${js(scope)}, ${name}, ${value});`];
  }

  private subgraphCalls(program: CompiledProgram, scope: string, node: CompiledNode): string[] {
    const graphId = prop(node, 'graph');
    const child = graphId ? program.subgraphs[graphId] : undefined;
    if (!child) return [];
    const childScope = `${scope}/${graphId}`;
    const lines: string[] = [];
    for (const id of child.entries.start) {
      lines.push('if (host.halted) return;');
      lines.push(`${this.execName(childScope, id)}(host);`);
    }
    return lines;
  }

  private customExec(scope: string, node: CompiledNode): string[] {
    const pins = Object.keys(node.dataIn);
    const readLines = pins.map((pin) => `  if (name === ${js(pin)}) return ${this.expr(scope, node, pin)};`);
    const followLines: string[] = [];
    for (const pin of Object.keys(node.execOut)) {
      followLines.push(`if (name === ${js(pin)}) {`);
      followLines.push(...indent(this.calls(scope, node.execOut[pin]), 2));
      followLines.push('  return;');
      followLines.push('}');
    }
    return [
      `host.scriptExec(${js(node.typeId)}, ${js(scope)}, ${js(node.id)}, (name) => {`,
      ...readLines,
      '  return undefined;',
      '}, (name) => {',
      ...indent(followLines, 2),
      '});',
    ];
  }

  private valueBody(scope: string, node: CompiledNode): string[] {
    const id = node.id;
    switch (node.typeId) {
      case 'core/OnUpdate':
        return ['if (pin === "dt") return host.dt;', 'return undefined;'];
      case 'core/OnEvent':
        return [`if (pin === "payload") return host.payload(${js(scope)}, ${js(id)});`, 'return undefined;'];
      case 'core/ForLoop':
        return [`if (pin === "index") return host.readLoop(${js(scope)}, ${js(id)});`, 'return undefined;'];
      case 'core/GetVariable':
        return this.readVariable(scope, node);
      case 'core/SetVariable':
        return [`if (pin === "result") return ${this.expr(scope, node, 'value')};`, 'return undefined;'];
      case 'core/Add':
      case 'core/Subtract':
      case 'core/Multiply':
      case 'core/Divide':
        return this.binary(scope, node, opFor(node.typeId));
      case 'core/Clamp':
        return [
          'if (pin !== "result") return undefined;',
          `return clamp(host.num(${this.expr(scope, node, 'value')}), host.num(${this.expr(scope, node, 'min')}), host.num(${this.expr(scope, node, 'max')}));`,
        ];
      case 'core/And':
        return [
          'if (pin !== "result") return undefined;',
          `return host.truthy(${this.expr(scope, node, 'a')}) && host.truthy(${this.expr(scope, node, 'b')});`,
        ];
      case 'core/Or':
        return [
          'if (pin !== "result") return undefined;',
          `return host.truthy(${this.expr(scope, node, 'a')}) || host.truthy(${this.expr(scope, node, 'b')});`,
        ];
      case 'core/Not':
        return ['if (pin !== "result") return undefined;', `return !host.truthy(${this.expr(scope, node, 'value')});`];
      case 'core/Equal':
        return [
          'if (pin !== "result") return undefined;',
          `return host.equal(${this.expr(scope, node, 'a')}, ${this.expr(scope, node, 'b')});`,
        ];
      case 'core/NotEqual':
        return [
          'if (pin !== "result") return undefined;',
          `return !host.equal(${this.expr(scope, node, 'a')}, ${this.expr(scope, node, 'b')});`,
        ];
      case 'core/Greater':
      case 'core/GreaterEqual':
      case 'core/Less':
      case 'core/LessEqual':
        return this.compare(scope, node, opFor(node.typeId));
      case 'core/Self':
        return ['if (pin === "entity") return host.world.self;', 'return undefined;'];
      case 'core/SpawnEntity':
        return [
          `if (pin === "entity") return host.spawned(${js(scope)}, ${js(node.id)});`,
          'return undefined;',
        ];
      case 'core/HasComponent':
        return [
          'if (pin !== "result") return undefined;',
          `return host.hasComponent(host.entity(${this.expr(scope, node, 'entity')}), ${js(prop(node, 'component'))});`,
        ];
      case 'core/Query':
        return [
          'if (pin !== "entities") return undefined;',
          `return host.query(${this.queryArg(scope, node)});`,
        ];
      case 'core/ForEach':
        return [
          `if (pin === "entity") return host.eachEntity(${js(scope)}, ${js(node.id)});`,
          'return undefined;',
        ];
      case 'core/GetComponent':
        return [
          'if (pin !== "value") return undefined;',
          `const component = ${js(prop(node, 'component'))};`,
          'if (!component) return undefined;',
          `return host.world.getComponent(host.entity(${this.expr(scope, node, 'entity')}), component);`,
        ];
      case 'core/GetField':
        return [
          'if (pin !== "value") return undefined;',
          `const component = ${js(prop(node, 'component'))};`,
          `const field = ${js(prop(node, 'field'))};`,
          'if (!component || !field) return undefined;',
          `return host.getField(host.entity(${this.expr(scope, node, 'entity')}), component, field);`,
        ];
      default:
        return this.customValue(scope, node);
    }
  }

  private queryArg(scope: string, node: CompiledNode): string {
    if (node.dataIn.components) return `host.componentNames(${this.expr(scope, node, 'components')})`;
    return js(componentNames(node.props.components));
  }

  private readVariable(scope: string, node: CompiledNode): string[] {
    const name = js(prop(node, 'name'));
    if (node.props.scope === 'entity') {
      return [
        'if (pin !== "value") return undefined;',
        `return host.entityGet(host.entity(${this.expr(scope, node, 'entity')}), ${name});`,
      ];
    }
    return ['if (pin !== "value") return undefined;', `return host.graphGet(${js(scope)}, ${name});`];
  }

  private binary(scope: string, node: CompiledNode, op: string): string[] {
    return [
      'if (pin !== "result") return undefined;',
      `return host.num(${this.expr(scope, node, 'a')}) ${op} host.num(${this.expr(scope, node, 'b')});`,
    ];
  }

  private compare(scope: string, node: CompiledNode, op: string): string[] {
    return [
      'if (pin !== "result") return undefined;',
      `return host.num(${this.expr(scope, node, 'a')}) ${op} host.num(${this.expr(scope, node, 'b')});`,
    ];
  }

  private customValue(scope: string, node: CompiledNode): string[] {
    const pins = Object.keys(node.dataIn);
    const readLines = pins.map((pin) => `  if (name === ${js(pin)}) return ${this.expr(scope, node, pin)};`);
    return [
      `return host.scriptValue(${js(node.typeId)}, ${js(scope)}, ${js(node.id)}, pin, (name) => {`,
      ...readLines,
      '  return undefined;',
      '});',
    ];
  }
}

function opFor(typeId: string): string {
  switch (typeId) {
    case 'core/Add':
      return '+';
    case 'core/Subtract':
      return '-';
    case 'core/Multiply':
      return '*';
    case 'core/Divide':
      return '/';
    case 'core/Greater':
      return '>';
    case 'core/GreaterEqual':
      return '>=';
    case 'core/Less':
      return '<';
    case 'core/LessEqual':
      return '<=';
    default:
      return '+';
  }
}
